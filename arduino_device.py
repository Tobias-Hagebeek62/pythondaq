"""Controller for experimental Arduino setup

This module contains multiple functions that can be used to run an experiment with an Arduino and a connected circuit.
"""

import numpy as np

# nodig voor de "mock-arduino"
import pandas as pd
import pyvisa

conversie = 1023 / 3.3  # van voltage naar ADC


def list_resources():
    """Port identifier

    Function that tells the user what device is connected to what port, and what it is called to properly recall it. Essential when switching hardware.

    Returns:
        List: Returns a list of devices currently connected via USB.
    """
    rm = pyvisa.ResourceManager("@py")
    ports = rm.list_resources()
    return ports


class ArduinoVISADevice:
    """Arduino controller

    Group of functions which allow the user to research an electrical circuit containing an LED and a resistance of 220 ohm. User can input in both Volt and ADC value and can receive the ADC values over the multiple volt-meters in the circuit
    """

    def __init__(self, port):
        """Defining the device

        This initial function allows setting up a profile which can be researched with the other functions in this class

        Args:
            port (String): The user can create a profile for a device currently connected to the device. The name of this device has to be put in, which is generated by list_resources()
        """
        self.port = port
        rm = pyvisa.ResourceManager("@py")
        self.device = rm.open_resource(
            self.port, read_termination="\r\n", write_termination="\n"
        )

    def get_identification(self):
        """Gives the identification of the corresponding profile

        Returns:
            String: Gives the identification of the corresponding profile
        """
        identification = self.device.query("*IDN?")
        self.idenfication = identification
        return self.idenfication

    def set_output_value(self, value):
        """LED brightness

        Sets LED to a certain ADC-value, which corresponds with a certain brightness

        Args:
            value (Integer): Value between 0 and 1023 which the LED will set to. These values correspond with a certain voltage.

        Returns:
            final_value: The brightness that the LED is currently set to. Does not get printed, and the user is better off using their input value
        """

        final_value = self.device.query(f"OUT:CH0 {value}")
        return final_value

    def set_output_voltage(self, voltage):
        """LED brightness

        Sets LED to a certain voltage, which corresponds with a certain brightness. Since the LED can only receive ADC values, the voltage given by the user is transformed into an ADC value and given to the LED.

        Args:
            voltage (Float): Sets the LED to a voltage. User has a range of 0 to 3.3, as the LED can not take light below 0 and can't handle more than 3.3V

        Returns:
            final_value: The brightness that the LED is currently set to. Does not get printed, and the user is better off using their input value
        """
        converted_voltage = int(voltage * conversie)
        final_value = self.device.query(f"OUT:CH0 {converted_voltage}")
        return final_value

    def get_output_value(self):
        """Measure current ADC value

        Gives current ADC value set by user. Useful when checking if commands are working and if software/hardware are working accordingly

        Returns:
            final_value: Gives current ADC value set by user
        """
        final_value = self.device.query("MEAS:CH0?")
        return final_value

    def get_output_voltage(self):
        """Measure current voltage

        Gives current voltage set by user. Useful when checking if commands are working and if software/hardware are working accordingly

        Returns:
            final_value: Gives current voltage set by user
        """
        final_voltage = self.device.query("MEAS:CH0?") / conversie
        return final_voltage

    def get_input_value(self, channel):
        """Measures ADC value over certain channel

        Measures the voltage in ADC values over a certain channel in the circuit. These are volt-meters in our setup

        Args:
            channel (Integer): User gives which channel he wants to measure

        Returns:
            channel_ADC: Current ADC value over the channel
        """
        channel_ADC = int(self.device.query(f"MEAS:CH{channel}?"))
        return channel_ADC

    def get_input_voltage(self, channel):
        """Measures voltage  over certain channel

        Measures the voltage in volt  over a certain channel in the circuit. These are volt-meters in our setup

        Args:
            channel (Integer): User gives which channel he wants to measure

        Returns:
            channel_ADC: Current voltage over the channel
        """
        channel_voltage = int(self.device.query(f"MEAS:CH{channel}?")) / conversie
        return channel_voltage


class ArduinoVISADeviceMock:
    def __init__(self, port):
        self.port = port
        self.is_simulated = port == "SIM"

        if self.is_simulated:
            print("[MOCK] Draait in simulatiemodus (thuis zonder hardware).")
            self.current_x = 0
            self.measurement_counter = {}
            try:
                self.df_mock = pd.read_csv("measurements.csv")
            except Exception:
                self.df_mock = None
        else:
            rm = pyvisa.ResourceManager("@py")
            self.device = rm.open_resource(
                self.port, read_termination="\r\n", write_termination="\n"
            )

    def get_identification(self):
        if self.is_simulated:
            return "Arduino Mock Device, Diode Experiment"
        return self.device.query("*IDN?")

    def set_output_value(self, value):
        self.current_x = int(value)
        if self.is_simulated:
            if self.current_x not in self.measurement_counter:
                self.measurement_counter[self.current_x] = 0
            return str(value)
        else:
            return self.device.query(f"OUT:CH0 {value}")

    def set_output_voltage(self, voltage):
        converted_voltage = int(voltage * conversie)
        return self.set_output_value(converted_voltage)

    def get_output_value(self):
        if self.is_simulated:
            return str(self.current_x)
        return self.device.query("MEAS:CH0?")

    def get_output_voltage(self):
        return float(self.get_output_value()) / conversie

    def get_input_value(self, channel):
        if self.is_simulated:
            conversie_val = 1023 / 3.3
            if self.df_mock is not None and len(self.df_mock) >= 3072:
                idx_base = self.current_x * 3
                sub_idx = self.measurement_counter.get(self.current_x, 0) % 3
                row_idx = min(idx_base + sub_idx, len(self.df_mock) - 1)
                self.measurement_counter[self.current_x] = sub_idx + 1

                row = self.df_mock.iloc[row_idx]
                voltage_led = row["Voltage"]
                current_res = row["Current"]
                v_res = current_res * 220

                if channel == 1:
                    val = (voltage_led + v_res) * conversie_val
                elif channel == 2:
                    val = v_res * conversie_val
                else:
                    val = 0
                return int(np.clip(val, 0, 1023))
            return 0
        else:
            return int(self.device.query(f"MEAS:CH{channel}?"))

    def get_input_voltage(self, channel):
        return self.get_input_value(channel) / conversie


